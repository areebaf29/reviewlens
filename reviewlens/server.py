def render(pipe, q):
    body = ""
    if q:
        a = pipe.ask(q)
        if a.abstained:
            body = f'<div class=card><div class=q>{html.escape(q)}</div><p>{html.escape(a.text)}</p></div>'
        else:
            kind = f"generated by {a.generator}" if a.generative else "extractive quotes, not generated"
            bcls = 'badge' if a.generative else 'badge ext'
            ev = "".join(f'<li>{html.escape(h.chunk.text)} <span class=cite>[{html.escape(h.chunk.id)}]</span> '
                         f'<span class=muted>similarity {h.dense:.2f}</span></li>' for h in a.sources)
            ans = re.sub(r'\[([^\]]+)\]', r'<span class=cite>[\1]</span>', html.escape(a.text)).replace("\n", "<br>")
            note = f'<p class=muted>{html.escape(a.note)}</p>' if a.note else ""
            if a.generative:
                note += ('<p class="muted warn">Citation ids are checked to exist, and a language-inference model removes statements '
                         'the cited reviews do not support. Neither is proof. Read the evidence below.</p>')
            body = (f'<div class=card><div class=q>{html.escape(q)}<span class="{bcls}">{html.escape(kind)}</span></div>'
                    f'<p>{ans}</p>{note}</div><div class=card><div class=q>Retrieved evidence</div><ul>{ev}</ul></div>')
    topics = mine_topics(pipe.store, k=5)
    t = "".join(f'<div class=topic><span>{html.escape(x.label)}</span><span class=muted>{x.size} chunks, avg {x.avg_rating:.1f}</span></div>' for x in topics)
    tb = f'<div class=card><div class=q>Top complaint themes (3 stars and below)</div>{t}</div>' if t else ""
    label = f'<div class=corpus><b>Review set:</b> {html.escape(pipe.corpus_label)}</div>' if getattr(pipe, "corpus_label", "") else ""
    return PAGE.replace("__LABEL__", label).replace("__Q__", html.escape(q, quote=True)).replace("__BODY__", body).replace("__TOPICS__", tb)


def serve(pipe, port=8000):
    class H(BaseHTTPRequestHandler):
        def do_GET(self):
            u = urlparse(self.path)
            q = (parse_qs(u.query).get("q") or [""])[0][:300]
            if u.path == "/api/ask":
                a = pipe.ask(q)
                data = json.dumps({"question": q, "answer": a.text, "abstained": a.abstained, "citations": a.citations,
                                   "generator": a.generator, "generative": a.generative,
                                   "sources": [{"id": h.chunk.id, "text": h.chunk.text, "similarity": round(h.dense, 3)} for h in a.sources]}).encode()
                ctype = "application/json"
            elif u.path == "/":
                data, ctype = render(pipe, q).encode(), "text/html; charset=utf-8"
            else:
                self.send_error(404)
                return
            self.send_response(200)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def log_message(self, *a):
            pass

    print(f"ReviewLens on http://127.0.0.1:{port}")
    ThreadingHTTPServer(("127.0.0.1", port), H).serve_forever()
